import assert from 'node:assert/strict';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {createServer} from 'vite';
import {chromium} from 'playwright';

const root=new URL('../',import.meta.url).pathname;
const server=await createServer({root,server:{host:'127.0.0.1',port:0},logLevel:'error'});
await server.listen();
const port=server.httpServer.address().port;
const browser=await chromium.launch({headless:true,
  ...(process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE}:{}),
  args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']});
const errors=[], results=[];
await mkdir(root+'docs',{recursive:true});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1150},deviceScaleFactor:1});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto(`http://127.0.0.1:${port}`,{waitUntil:'networkidle'});
  await page.locator('canvas[data-ready="true"]').waitFor();
  await page.evaluate(()=>document.fonts.ready);
  await page.screenshot({path:root+'docs/preview-desktop.png',fullPage:true});
  await page.locator('canvas').screenshot({path:root+'docs/preview-scene.png'});
  const atlasPixels=await page.locator('canvas').evaluate(c=>Array.from(c.getContext('2d').getImageData(0,0,c.width,c.height).data));
  await page.getByLabel('Sprite source').selectOption('sprites');
  await page.waitForFunction(()=>document.querySelector('#renderer').value==='sprites');
  await page.evaluate(()=>new Promise(requestAnimationFrame));
  const pngPixels=await page.locator('canvas').evaluate(c=>Array.from(c.getContext('2d').getImageData(0,0,c.width,c.height).data));
  assert.equal(atlasPixels.length,pngPixels.length);
  let difference=0,maxDelta=0;
  atlasPixels.forEach((v,i)=>{const d=Math.abs(v-pngPixels[i]);difference+=d;maxDelta=Math.max(maxDelta,d);});
  assert.ok(difference/atlasPixels.length<.3,`Atlas/PNG mean difference ${difference/atlasPixels.length}`);
  results.push({check:'atlas / individual PNG parity',meanChannelDelta:difference/atlasPixels.length,maxChannelDelta:maxDelta});
  await page.getByLabel('Sprite source').selectOption('atlas');
  for(const label of ['Grid','Anchors','Collisions'])await page.getByLabel(label,{exact:true}).check();
  await page.locator('canvas').screenshot({path:root+'docs/preview-guides.png'});
  for(const label of ['Grid','Anchors','Collisions'])await page.getByLabel(label,{exact:true}).uncheck();
  await page.getByRole('button',{name:'Sprite cuts',exact:true}).click();
  await page.locator('canvas').screenshot({path:root+'docs/preview-cuts.png'});
  await page.getByRole('button',{name:'Atlas',exact:true}).click();
  await page.locator('canvas').screenshot({path:root+'docs/preview-atlas.png'});
  await page.getByRole('button',{name:'Scene',exact:true}).click();
  await page.getByLabel('Scene preset').selectOption('stress');
  await page.locator('canvas').screenshot({path:root+'docs/preview-stress.png'});
  await page.getByLabel('Scene preset').selectOption('contact');
  await page.getByRole('button',{name:/Coral block/}).click();
  await page.locator('canvas').screenshot({path:root+'docs/preview-contact.png'});
  await page.screenshot({path:root+'docs/preview-contact-desktop.png',fullPage:true});
  assert.ok((await page.locator('.stage-footer').innerText()).includes('54 objects'));
  results.push({check:'solid block contact preset',ok:true});
  await page.getByRole('button',{name:/Orchard tree/}).click();
  await page.getByLabel('Scene preset').selectOption('village');
  const before=await page.locator('.stage-footer').innerText();
  await page.getByRole('button',{name:'Place',exact:true}).click();
  const canvas=page.locator('canvas'), bounds=await canvas.boundingBox();
  const W=bounds.width, s=Math.min(72,(W-32)/11), top=108*s/64+18,left=(W-11*s)/2;
  await canvas.click({position:{x:left+6.5*s,y:top+10.5*s}});
  assert.ok((await page.getByRole('status').innerText()).includes('Placed tree'));
  const after=await page.locator('.stage-footer').innerText();
  assert.notEqual(before,after);
  await page.getByRole('button',{name:'Undo last edit'}).click();
  assert.equal(await page.locator('.stage-footer').innerText(),before);
  results.push({check:'cell placement and undo',ok:true});
  await page.getByRole('button',{name:'Inspect',exact:true}).click();
  const downloadJSON=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export scene JSON'}).click();
  const sceneDownload=await downloadJSON;
  const scenePath=await sceneDownload.path();
  const scene=JSON.parse(await readFile(scenePath,'utf8'));
  assert.equal(scene.objects.length,54);
  await page.locator('input[type=file]').setInputFiles({name:'valid-scene.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({...scene,name:'Imported village'}))});
  await page.waitForFunction(()=>document.querySelector('[role=status]').textContent.includes('valid-scene.json'));
  assert.ok((await page.getByRole('status').innerText()).includes('Loaded valid-scene.json'));
  await page.locator('input[type=file]').setInputFiles({name:'invalid-scene.json',mimeType:'application/json',buffer:Buffer.from('{"width":-1}')});
  await page.waitForFunction(()=>document.querySelector('[role=status]').textContent.includes('Import failed'));
  assert.ok((await page.getByRole('status').innerText()).includes('Import failed'));
  await page.getByRole('button',{name:'Undo last edit'}).click();
  const downloadPNG=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export preview PNG'}).click();
  const pngDownload=await downloadPNG;
  assert.equal(pngDownload.suggestedFilename(),'tile-foundry-scene.png');
  results.push({check:'scene JSON and preview PNG downloads, valid/invalid import',ok:true});
  await page.getByRole('button',{name:'Workflows',exact:true}).click();
  await page.locator('.workflow-preview[data-ready="true"]').first().waitFor();
  assert.equal(await page.locator('.workflow-card').count(),4);
  assert.equal(await page.locator('.workflow-preview[data-ready="true"]').count(),4);
  await page.locator('.workflow-cards').screenshot({path:root+'docs/preview-workflows.png'});
  await page.locator('.material-scene[data-ready="true"]').screenshot({path:root+'docs/preview-material-scene.png'});
  await page.screenshot({path:root+'docs/preview-workflows-desktop.png',fullPage:true});
  await page.getByLabel('SVG outline',{exact:true}).check();
  await page.getByLabel('Material variant').selectOption('wood');
  await page.getByLabel('SVG height').selectOption('96');
  await page.locator('[data-workflow="3"] canvas[data-ready="true"]').waitFor();
  assert.ok((await page.locator('[data-workflow="3"]').innerText()).includes('224 / 224 px'));
  assert.equal(await page.locator('[data-workflow="3"] dd').last().innerText(),'Yes');
  await page.locator('[data-workflow="3"]').screenshot({path:root+'docs/preview-svg-wood-96.png'});
  const materialDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export this scene PNG'}).click();
  assert.equal((await materialDownload).suggestedFilename(),'svg-material-scene.png');
  results.push({check:'four workflow cards, live wood/96px variant, SVG overlay, mixed-height PNG export',ok:true});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>new Promise(requestAnimationFrame));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Workflow mobile overflow');
  await page.locator('[data-workflow="3"]').screenshot({path:root+'docs/preview-workflows-mobile.png'});
  await page.setViewportSize({width:320,height:844});
  await page.evaluate(()=>new Promise(requestAnimationFrame));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Workflow 320px overflow');
  results.push({check:'workflow lab at 390px and 320px',ok:true});
  await page.setViewportSize({width:390,height:844});
  await page.reload({waitUntil:'networkidle'});
  await page.locator('canvas[data-ready="true"]').waitFor();
  await page.evaluate(()=>new Promise(requestAnimationFrame));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Mobile horizontal overflow');
  await page.screenshot({path:root+'docs/preview-mobile.png',fullPage:true});
  results.push({check:'390px mobile viewport',ok:true});
  await page.setViewportSize({width:320,height:844});
  await page.evaluate(()=>new Promise(requestAnimationFrame));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'320px horizontal overflow');
  results.push({check:'320px narrow viewport',ok:true});
  assert.deepEqual(errors,[],'Browser errors');
  await writeFile(root+'docs/browser-verification.json',JSON.stringify({ok:true,results,errors},null,2)+'\n');
  console.log(JSON.stringify({ok:true,results,errors},null,2));
}finally{await browser.close();await server.close();}
